#!/usr/bin/env python3
"""extract.py SRC.c OUT.h FUNC [FUNC ...]: copy the definitions (signature through the closing brace) of static
functions of a driver .c into OUT.h, so a binoracle block can test code that does not live in a header (openimp #553).
Exit 1 if a definition is not found."""
import re, sys

src, out, funcs = sys.argv[1], sys.argv[2], sys.argv[3:]
t = open(src).read()
parts = ['/* generated by tests/t31_binoracle/extract.py from %s */\n' % src.split('/')[-1]]
for f in funcs:
    for m in re.finditer(r'^static[^;{()]*\b%s\(' % re.escape(f), t, re.M):
        i = t.index('(', m.end() - 1); d = 0
        while True:                        # skip the parameter list
            d += {'(': 1, ')': -1}.get(t[i], 0); i += 1
            if d == 0:
                break
        j = i
        while t[j] in ' \t\n' or t.startswith('/*', j):     # blanks and comments after the parameter list
            j = t.index('*/', j) + 2 if t.startswith('/*', j) else j + 1
        if t[j] != '{':                    # a prototype
            continue
        d = 0
        while True:
            d += {'{': 1, '}': -1}.get(t[j], 0); j += 1
            if d == 0:
                break
        parts.append(t[m.start():j] + '\n')
        break
    else:
        sys.exit('extract.py: no definition of %s in %s' % (f, src))
open(out, 'w').write('\n'.join(parts))
