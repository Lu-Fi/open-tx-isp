static inline void t33_swdmsc_put(const struct t33_swdmsc_ops *o, u32 ch, u8 cfg, const u32 *v,
				  const struct t33_swdmsc_wr *t, unsigned int n)
{
	unsigned int k;
	u32 reg;

	for (k = 0; k < n; k++) {
		reg = cfg ? t[k].idx : t[k].addr;
		o->reg_write(ch, 9, reg, t33_swdmsc_val(v, t[k].idx));
	}
}

/*
 * tisp_dmsc_switch_para: v = dmscInfo[ch] words, tparams = tparamsP[ch],
 * cfg = dmscCfgMode, refresh = tispDmscRefresh.  Returns 0.
 */
static inline int t33_dmsc_switch_para(const struct t33_swdmsc_ops *o, u32 ch, u32 *v, u32 tparams,
				       u8 cfg, u8 *refresh)
{
	u32 gain, i, f;
	const u8 *sec;
	unsigned int k;

	ch &= 0xff;
	v[670] = tparams + 17900;
	gain = v[671];
	o->bin_par_update(ch);
	sec = (const u8 *)(uintptr_t)v[670];
	i = (u32)((int)gain >> 16);
	f = gain & 0xffff;
	for (k = 0; k < ARRAY_SIZE(t33_swdmsc_itp); k++)
		v[t33_swdmsc_itp[k].word >> 2] = t33_swdmsc_itp[k].wide ?
			o->intp16(i, f, sec + t33_swdmsc_itp[k].sec) :
			o->intp8(i, f, sec + t33_swdmsc_itp[k].sec);
	v[168 >> 2] = o->ratio(W(2688) & 0xff, W(168), 600);
	v[172 >> 2] = o->ratio(W(2688) & 0xff, W(172), 600);
	v[256 >> 2] = o->ratio(W(2688) & 0xff, W(256), 600);
	v[260 >> 2] = o->ratio(W(2688) & 0xff, W(260), 600);
	v[716 >> 2] = o->ratio(W(2688) & 0xff, W(716), 600);
	o->para_update(ch);
	if (o->dma_state(9)) {
		*refresh = 2;
		return 0;
	}
	t33_swdmsc_put(o, ch, cfg, v, t33_swdmsc_wr1, ARRAY_SIZE(t33_swdmsc_wr1));
	t33_swdmsc_put(o, ch, cfg, v, t33_swdmsc_wr2, ARRAY_SIZE(t33_swdmsc_wr2));
	o->reg_write(ch, 9, cfg ? 1 : 0x8010, 1);
	*refresh = 1;
	return 0;
}

