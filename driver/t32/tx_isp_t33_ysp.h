/*
 * Block init at gain (16.16) into list l (capacity cap words); v:
 * T33_YSP_WORDS words of block state.  Returns the list length.
 */
static inline int t33_ysp_init(const u8 *sec, u32 gain, u32 *v, u32 *l, u32 cap)
{
	int len = t33_rcfg_tmpl_init(l, cap, t33_ysp_tmpl, ARRAY_SIZE(t33_ysp_tmpl));
	unsigned int k;

	for (k = 0; k < T33_YSP_WORDS; k++)
		v[k] = 0;
	t33_vb_bin(v, sec, t33_ysp_bin, ARRAY_SIZE(t33_ysp_bin));
	t33_vb_intp(v, sec, gain, t33_ysp_intp, ARRAY_SIZE(t33_ysp_intp));
	t33_ysp_reg_data(v);
	if (len > 0)
		t33_ysp_store(v, l);
	return len;
}

