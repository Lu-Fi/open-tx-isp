/*
 * tisp_dpc_init at gain (16.16) into list l (capacity cap words);
 * v: T33_DPC_WORDS words of block state.  Returns the list length.
 */
static inline int t33_dpc_init(const u8 *sec, u32 gain, u32 *v, u32 *l, u32 cap)
{
	int len = t33_rcfg_tmpl_init(l, cap, t33_dpc_tmpl, ARRAY_SIZE(t33_dpc_tmpl));
	unsigned int k;

	for (k = 0; k < T33_DPC_WORDS; k++)
		v[k] = 0;
	t33_vb_bin(v, sec, t33_dpc_bin, ARRAY_SIZE(t33_dpc_bin));
	t33_vb_intp(v, sec, gain, t33_dpc_intp, ARRAY_SIZE(t33_dpc_intp));
	t33_dpc_para(v);
	t33_vb_copy(v, t33_dpc_copy, ARRAY_SIZE(t33_dpc_copy));
	if (len > 0)
		t33_dpc_store(v, l);
	return len;
}

