/* func_dpc_para_update: range limits and the correction level switch */
static inline void t33_dpc_para(u32 *v)
{
	u32 lo = v[0x20], hi = v[0x21], lvl = v[10];

	v[0x72] = v[0x1b] - lo;
	v[0x76] = v[0x1f] + hi;
	v[0x6e] = v[0x17] + hi;
	v[0x6b] = v[0x12] - v[0x14];
	v[0x6d] = v[0x16] - lo;
	v[0x6f] = v[0x18] - lo;
	v[0x70] = v[0x19] - lo;
	v[0x71] = v[0x1a] - lo;
	v[0x73] = v[0x1c] + hi;
	v[0x74] = v[0x1d] + hi;
	v[0x75] = v[0x1e] + hi;
	v[0x6c] = v[0x15] + v[0x13];
	v[0x77] = v[0x22] - v[0x24];
	v[0x78] = v[0x25] + v[0x23];
	/* level 0..4 enables (81, 82, 83, 84, 89, 90, 91, 95, 96, 99) */
	v[0x51] = lvl >= 1;
	v[0x52] = lvl >= 2;
	v[0x53] = lvl >= 3;
	v[0x54] = lvl >= 4;
	v[0x59] = lvl >= 2;
	v[0x5a] = lvl >= 3;
	v[0x5b] = lvl >= 4;
	v[0x5f] = lvl >= 3;
	v[0x60] = lvl >= 4;
	v[99] = lvl >= 4;
	v[0x8b] = 0x200;
}

