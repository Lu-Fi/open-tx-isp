/*
 * 1 when every row selector of the section stays inside the table.  tisp_rdns_intp interpolates each selector between two
 * neighbouring table entries (or takes entry 10), so the parameter bytes 0..2 stay below 128 for every gain exactly then.
 */
static inline int t32_rdns_rows_ok(const u8 *sec)
{
	unsigned int i;

	for (i = 0; i < T32_RDNS_TAB_SEL; i++)
		if (sec[T32_RDNS_SEC_U8(0) + i] >= T32_RDNS_TAB_ROWS)
			return 0;
	return 1;
}

/*
 * The context as the vendor's tisp_rdns_init leaves it, on a section copy sec instead of the tuning base (the driver keeps no
 * tuning base): zeroed context and parameter block, the row table, gain none, then tisp_rdns_par_refresh at unity gain (all
 * registers, gain 0x10000 stored) and the block id write.  Returns the number of writes in w (t32_rdns_init's writes).
 */
static inline int t32_rdns_ctx_init(struct t32_rdns_ctx *ctx, u8 *sec, u8 *param, struct t32_front_write *w)
{
	unsigned int n = 0;

	memset(ctx, 0, sizeof(*ctx));
	memset(param, 0, T32_RDNS_PARAM_BYTES);
	ctx->sec = sec;
	ctx->param = param;
	ctx->rows = (const u8 *)t32_rdns_tab_c0ac0;
	ctx->gain = T32_RDNS_GAIN_NONE;
	t32_rdns_par_refresh_n(ctx, T32_RDNS_GAIN_UNITY, T32_RDNS_REFRESH_THRESHOLD, w, &n);
	T32_FWR(w, n, T32_RDNS_REG_ID, T32_RDNS_ID);
	return (int)n;
}

