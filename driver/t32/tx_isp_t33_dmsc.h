/*
 * tisp_dmsc_par_refresh at gain (16.16) into list l (capacity cap words);
 * v: T33_DMSC_WORDS words of block state.  Returns the list length.
 */
static inline int t33_dmsc_init(const u8 *sec, u32 gain, u32 *v, u32 *l, u32 cap)
{
	int len = t33_rcfg_tmpl_init(l, cap, t33_dmsc_tmpl, ARRAY_SIZE(t33_dmsc_tmpl));
	unsigned int k;

	for (k = 0; k < T33_DMSC_WORDS; k++)
		v[k] = 0;
	t33_vb_bin(v, sec, t33_dmsc_bin, ARRAY_SIZE(t33_dmsc_bin));
	t33_vb_intp(v, sec, gain, t33_dmsc_intp, ARRAY_SIZE(t33_dmsc_intp));
	t33_vb_copy(v, t33_dmsc_copy, ARRAY_SIZE(t33_dmsc_copy));
	t33_dmsc_para(v);
	if (len > 0)
		t33_dmsc_store(v, l);
	return len;
}

