/*
 * func_rdns_para_update after the copies; blc: BLC list slot 3 (0x3044),
 * dg: DG list slot 3 (0x4060), as the vendor reads them with
 * tisp_reg_read_t33.
 */
static inline void t33_rdns_para(u32 *v, u32 blc, u32 dg)
{
	t33_rdns_val_lut((int)v[0x4a], v[0x47], &v[0xa8]);
	t33_rdns_val_lut((int)v[0x49], v[0x46], &v[0xac]);
	t33_rdns_val_lut((int)v[0x4b], v[0x48], &v[0xb0]);
	v[0xb4] = v[0x4c];
	v[0xb5] = blc & 0xffff;
	v[0xb6] = (dg & 0xffff) >> 4;
	/* isp_rdns_update_value_ks (8, 4 / 5, 1) */
	t33_itp_ks(t33_iabs((int)(v[0x5d] - v[0x5c])), t33_iabs((int)(v[0x5b] - v[0x5a])), 5, 9, &v[200], &v[0xce]);
	t33_itp_ks(t33_iabs((int)(v[0x61] - v[0x60])), t33_iabs((int)(v[0x5f] - v[0x5e])), 6, 9, &v[0xcd], &v[0xcf]);
}

