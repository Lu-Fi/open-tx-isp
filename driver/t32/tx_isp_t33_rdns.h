/* rdns_sigma_quantify */
static inline int t33_rdns_sigma_q(int x)
{
	if (x > 0x3f) {
		if (x < 0x80)
			x = (x - 0x30) * 4;
		else if (x < 0xc0)
			x = (x - 0x6c) * 0x10;
		else
			x = (x - 0xab) * 0x40;
	}
	return x < 0x1000 ? x : 0xfff;
}

/* rdns_func_val_lut: four thresholds from sigma and strength (weights as SDNS) */
static inline void t33_rdns_val_lut(int sigma, u32 str, u32 *out)
{
	int s = t33_rdns_sigma_q(sigma), q = t33_rdns_str_q[str & 0xff], d;
	unsigned int k;

	for (k = 0; k < 4; k++) {
		/* s^2 - (u32)((-w * q^2) >> 23), the vendor's 64-bit product */
		d = s * s - (int)(u32)((unsigned long long)(-(long long)t33_sdns_w[k] * (long long)(q * q)) >> 23);
		out[k] = d < 0xffe001 ? (u32)t33_fix_sqrt(d, 1, 17) : 0xfff;
	}
}

