/*
 * Block init at gain (16.16) into list l (capacity cap words); v:
 * T33_RDNS_WORDS words of block state.  Returns the list length.
 */
static inline int t33_rdns_init(const u8 *sec, u32 gain, u32 ev, u32 blc, u32 dg, u32 *v, u32 *l, u32 cap)
{
	int len = t33_rcfg_tmpl_init(l, cap, t33_rdns_tmpl, ARRAY_SIZE(t33_rdns_tmpl));
	unsigned int k;

	for (k = 0; k < T33_RDNS_WORDS; k++)
		v[k] = 0;
	t33_vb_bin(v, sec, t33_rdns_bin, ARRAY_SIZE(t33_rdns_bin));
	t33_vb_evintp(v, sec, ev, sec + 0x39c, t33_rdns_evintp, ARRAY_SIZE(t33_rdns_evintp));
	t33_vb_intp(v, sec, gain, t33_rdns_intp, ARRAY_SIZE(t33_rdns_intp));
	t33_vb_copy(v, t33_rdns_copy, ARRAY_SIZE(t33_rdns_copy));
	t33_rdns_para(v, blc, dg);
	if (len > 0)
		t33_rdns_store(v, l);
	return len;
}

