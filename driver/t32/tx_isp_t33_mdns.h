/* func_igaussian_int: sqrt(x * 2 s^2 >> 24), 0x800 from 0x400000 on */
static inline int t33_mdns_igauss(u32 x, u32 s)
{
	long long p;
	int r;

	if (!s)
		return 0;
	p = (long long)x * (long long)(2ULL * s * s);
	r = (int)(p >> 24);
	if (r >= 0x400000)
		return 0x800;
	return r > 1 ? t33_fix_sqrt(r, 1, 17) : r;
}

/* func_update_nlm_lut_by_sigma_int: 15 weights, rounded >> sh, at most 2^(11 - sh) - 1 */
static inline int t33_mdns_nlm_lut(u32 sigma, void *outp, const void *flagp, int unused, u32 sh)
{
	u32 *out = outp, max = (1U << (11 - sh)) - 1;
	const int *flag = flagp;
	int d = 1 << sh, k, q;

	(void)unused;
	for (k = 0; k < 15; k++) {
		if (!flag[k])
			return k;
		q = (t33_mdns_igauss(t33_mdns_nlm_x[k], t33_mdns_nlm_sigma[sigma & 0xff]) + d / 2) / d;
		out[k] = q < 0 ? 0 : (u32)q > max ? max : (u32)q;
	}
	return 15;
}

/* func_sort_L2H: ascending bubble sort of n ints */
static inline void t33_mdns_sort(void *p, int n)
{
	int *a = p, i, j, t;

	for (i = 0; i < n; i++)
		for (j = 0; j < n - 1 - i; j++)
			if (a[j + 1] < a[j]) {
				t = a[j];
				a[j] = a[j + 1];
				a[j + 1] = t;
			}
}

/*
 * isp_itp_update_ks: the largest shift smax..smin with (a << s + b / 2) / b
 * negative or below 2^bits; val / shift stay as they are when none fits.
 */
static inline void t33_mdns_itp_ks(int a, int b, u32 bits, int smin, int smax, u32 *val, u32 *shift)
{
	u32 max = (1U << bits) - 1, q;
	int s, d;

	if (b < 1)
		return;
	if (b == 1) {
		*val = 0;
		*shift = (u32)smin;
		return;
	}
	for (s = smax; s >= smin; s--) {
		if (s < 0) {
			d = b << -s;
			q = (u32)(((d >> 1) + a) / d);
		} else {
			q = (u32)(((a << s) + (b >> 1)) / b);
		}
		if ((int)q < 0 || q <= max) {
			*val = q;
			*shift = (u32)s;
			return;
		}
	}
}

/* isp_mdns_update_value_ks: one segment (x[0..1], y[0..1]) */
