#!/usr/bin/env python3
# genadr.py <workdir> <oem.ko> <objdump> <out.inc>
import sys, re, subprocess
W, KO, OD, OUT = sys.argv[1:5]
fns = open(f"{W}/adr/fnlist").read().split()
syms = {}
for l in open(f"{W}/prod.sym"):
    p = l.split()
    if len(p) >= 6 and p[2] == 'O' and p[3] in ('.bss', '.data', '.rodata'):
        syms[p[5]] = (p[3], int(p[0], 16), int(p[4], 16))
SHARED = {'tparamsN', 'tispinfo'}
EXT = {  # OEM external -> handled in the dispatcher
 'system_reg_write','system_reg_read','memcpy','memset','private_vmalloc','private_vfree',
 'private_raw_mutex_init','private_mutex_lock','private_mutex_unlock','private_dma_cache_sync',
 'isp_printf','system_irq_func_set','tisp_event_set_cb','tisp_event_push','__ashldi3',
 '__lshrdi3','div64_u64'}
bodies = {}
used = set()
for f in fns:
    t = open(f"{W}/adr/{f}.c").read().split('\n')
    t = [l for l in t if not l.startswith('/*')]
    b = '\n'.join(t)
    for m in re.finditer(r'&([A-Za-z_$][A-Za-z_0-9$]*)', b):
        used.add(m.group(1))
    bodies[f] = b
priv = sorted(s for s in used if s in syms and s not in SHARED)
# section bytes for .data/.rodata
def secbytes(sec):
    out = subprocess.run([OD, '-s', '-j', sec, KO], capture_output=True, text=True).stdout
    data = {}
    for l in out.split('\n'):
        m = re.match(r'\s*([0-9a-f]+) ((?:[0-9a-f]{2,8} ){1,4})', l)
        if not m: continue
        a = int(m.group(1), 16)
        hx = ''.join(m.group(2).split())
        for i in range(0, len(hx), 2):
            data[a + i // 2] = int(hx[i:i+2], 16)
    return data
secs = {s: secbytes(s) for s in ('.data', '.rodata')}
o = []
o.append('''/*
 * Literal mips2c ADR (adaptive dynamic range / highlight compression) chain
 * from the OEM sc830ai tx-isp-t40.ko: tisp_adr_main_init with all refresh /
 * base_pars / 5x5 / gauss helpers, tiziano_adr_main_interrupt_static,
 * tisp_adr_main_process with algorithm / ev_func / Tiziano_adr_fpga /
 * subsection_* / fix_point_* and the four register writers.  Generated by
 * tools/gen_t40_adr_lit.py with tools/mips2c_literal.py (mult/madd, full
 * HI16/LO16 section addresses, runtime call dispatch); 0 unmapped
 * addresses, 0 unhandled opcodes.
 *
 * Why: the recovered ADR lift writes registers through a broken chain
 * (unmatched jr.hb tail calls drop the last write of func_adr_reg_write_one
 * and _5x5; madd/div results lost in 5x5_out / base_pars; func_gauss_local
 * is "return 0" in every build) and several ADR objects are smaller than
 * the OEM ones (adr_gauss_local 4 vs 96 B, adr_cut_base_up 4 vs 44 B,
 * width/height/count_adr_test 4 vs 8 B), so TOP bit 7 stayed bypassed.
 *
 * All ADR state is private here (adrlit_*, OEM sizes, OEM .data initial
 * bytes); only tparamsN and tispinfo are shared.  The functions share one
 * emulated MIPS stack per entry context (init / ISR / event), so stack
 * arguments reach callees as in the OEM.  Every jalr goes through
 * adrlit_dispatch() on the register value.  Active only with t40_adr_on=1
 * and t40_gates_oem_offset=1; TOP bit 7 is cleared only when the init
 * returned 0.  The ISR runs only from its own status bit 9 (the forced
 * fan-out path is blocked while this chain is active); the process runs
 * only from event 2.
 */
static bool regtrace_t40_adr_on;
module_param_named(t40_adr_on, regtrace_t40_adr_on, bool, 0644);
MODULE_PARM_DESC(t40_adr_on, "1 (with t40_gates_oem_offset=1) runs the literal OEM ADR chain and clears TOP bit 7 after a successful init (default 0)");
static bool regtrace_t40_adr_lit_active;
static int regtrace_adr_lit_init_ret = -1;
static unsigned int regtrace_adr_lit_isr_count, regtrace_adr_lit_process_count;
static unsigned int regtrace_adr_lit_bad_call, regtrace_adr_lit_forced_blocked;
static uint32_t regtrace_adr_lit_bad_target;
module_param_named(adr_lit_init_ret, regtrace_adr_lit_init_ret, int, 0444);
module_param_named(adr_lit_isr_count, regtrace_adr_lit_isr_count, uint, 0444);
module_param_named(adr_lit_process_count, regtrace_adr_lit_process_count, uint, 0444);
module_param_named(adr_lit_bad_call, regtrace_adr_lit_bad_call, uint, 0444);
module_param_named(adr_lit_bad_target, regtrace_adr_lit_bad_target, uint, 0444);
module_param_named(adr_lit_forced_blocked, regtrace_adr_lit_forced_blocked, uint, 0444);

static struct mutex adrlit_adr_mlock;
/* kernel libgcc helpers by asm label, so the lifted code's implicit uses
 * of the same names keep compiling */
extern char adrlit_lshrdi3_sym[] __asm__("__lshrdi3");
extern char adrlit_div64_u64_sym[] __asm__("div64_u64");
extern unsigned long long adrlit_div64_u64(unsigned long long, unsigned long long) __asm__("div64_u64");
static const char adrlit_str[] = "adr";
''')
for s in priv:
    sec, a, z = syms[s]
    if s == 'adr_mlock':
        continue
    if sec == '.bss':
        o.append(f"static uint8_t adrlit_{s}[{max(z,1)}] __attribute__((aligned(8)));")
    else:
        b = secs[sec]
        vals = ', '.join(f"0x{b.get(a+i,0):02x}" for i in range(z))
        o.append(f"static uint8_t adrlit_{s}[{max(z,1)}] __attribute__((aligned(8))) = {{ {vals} }};")
# anonymous .rodata constants (local array initialisers): private copies up
# to the next referenced constant / named object
anon = sorted({int(m, 16) for b in bodies.values()
               for m in re.findall(r'/\*UNMAPPED \.rodata\+0x([0-9a-f]+)\*/0', b)})
ro_starts = sorted(a for (sec, a, z) in syms.values() if sec == '.rodata')
for i, a in enumerate(anon):
    nxt = [x for x in ro_starts if x > a] + ([anon[i+1]] if i + 1 < len(anon) else [])
    z = min(min(nxt) - a if nxt else 256, 1024)
    b = secs['.rodata']
    vals = ', '.join(f"0x{b.get(a+k,0):02x}" for k in range(z))
    o.append(f"static const uint8_t adrlit_ro_{a:x}[{z}] __attribute__((aligned(8))) = {{ {vals} }};")
o.append('')
for f in fns:
    o.append(f"static int32_t {f}_lit(uint32_t a0_in, uint32_t a1_in, uint32_t a2_in, uint32_t a3_in, uint32_t sp_in, uint32_t *v1_out);")
o.append("static uint32_t adrlit_dispatch(uint32_t fn, uint32_t a0, uint32_t a1, uint32_t a2, uint32_t a3, uint32_t sp, uint32_t *v1);")
o.append("#define ADR_DISPATCH(r) adrlit_dispatch((r), r_a0, r_a1, r_a2, r_a3, r_sp, &r_v1)")
o.append('')
def fix(b):
    b = re.sub(r'/\*UNMAPPED \.rodata\+0x([0-9a-f]+)\*/0', lambda m: f'adrlit_ro_{m.group(1)}', b)
    b = re.sub(r'&\$LC\d+', 'adrlit_str', b)
    b = b.replace('&.sbss', 'adrlit_str')	# lock_class_key of mutex_init, unused here
    b = b.replace('&__lshrdi3', 'adrlit_lshrdi3_sym').replace('&div64_u64', 'adrlit_div64_u64_sym')
    def rp(m):
        n = m.group(1)
        if n == 'adr_mlock': return '&adrlit_adr_mlock'
        if n in priv: return f'adrlit_{n}'
        return m.group(0)
    return re.sub(r'&([A-Za-z_][A-Za-z_0-9]*)', rp, b)
for f in fns:
    o.append(f'''static int32_t {f}_lit(uint32_t a0_in, uint32_t a1_in, uint32_t a2_in, uint32_t a3_in, uint32_t sp_in, uint32_t *v1_out)
{{
    uint32_t r_v0 = 0, r_v1 = 0;
    uint32_t r_t0 = 0, r_t1 = 0, r_t2 = 0, r_t3 = 0, r_t4 = 0, r_t5 = 0;
    uint32_t r_t6 = 0, r_t7 = 0, r_t8 = 0, r_t9 = 0;
    uint32_t r_s0 = 0, r_s1 = 0, r_s2 = 0, r_s3 = 0, r_s4 = 0, r_s5 = 0;
    uint32_t r_s6 = 0, r_s7 = 0, r_s8 = 0, r_ra = 0, r_at = 0;
    uint32_t mips_lo = 0, mips_hi = 0, mips_cond = 0;
    uint32_t r_a0 = a0_in, r_a1 = a1_in, r_a2 = a2_in, r_a3 = a3_in;
    uint32_t r_sp = sp_in;

    (void)r_at; (void)r_ra; (void)r_t8; (void)r_t9; (void)mips_lo; (void)mips_hi;
    (void)mips_cond;
{fix(bodies[f])}
fn_exit:
    if (v1_out)
        *v1_out = r_v1;
    return (int32_t)r_v0;
}}
''')
# dispatcher
d = ['''static uint32_t adrlit_dispatch(uint32_t fn, uint32_t a0, uint32_t a1, uint32_t a2, uint32_t a3, uint32_t sp, uint32_t *v1)
{''']
for f in fns:
    d.append(f"    if (fn == (uint32_t)(uintptr_t)&{f})\n        return (uint32_t){f}_lit(a0, a1, a2, a3, sp, v1);")
d.append('''    if (fn == (uint32_t)(uintptr_t)&system_reg_write)
        return (uint32_t)system_reg_write(a0, a1);
    if (fn == (uint32_t)(uintptr_t)&system_reg_read)
        return (uint32_t)system_reg_read(a0);
    if (fn == (uint32_t)(uintptr_t)&memcpy)
        return (uint32_t)(uintptr_t)memcpy((void *)(uintptr_t)a0, (const void *)(uintptr_t)a1, a2);
    if (fn == (uint32_t)(uintptr_t)&memset)
        return (uint32_t)(uintptr_t)memset((void *)(uintptr_t)a0, (int)a1, a2);
    if (fn == (uint32_t)(uintptr_t)&private_vmalloc)
        return (uint32_t)(uintptr_t)vmalloc(a0);
    if (fn == (uint32_t)(uintptr_t)&private_vfree) {
        vfree((void *)(uintptr_t)a0);
        return 0;
    }
    if (fn == (uint32_t)(uintptr_t)&private_raw_mutex_init) {
        if (a0 == (uint32_t)(uintptr_t)&adrlit_adr_mlock)
            mutex_init(&adrlit_adr_mlock);
        return 0;
    }
    if (fn == (uint32_t)(uintptr_t)&private_mutex_lock) {
        mutex_lock((struct mutex *)(uintptr_t)a0);
        return 0;
    }
    if (fn == (uint32_t)(uintptr_t)&private_mutex_unlock) {
        mutex_unlock((struct mutex *)(uintptr_t)a0);
        return 0;
    }
    if (fn == (uint32_t)(uintptr_t)&private_dma_cache_sync) {
        if (a1 && a2)
            dma_cache_sync((void *)(uintptr_t)a0, (void *)(uintptr_t)a1, a2, (enum dma_data_direction)a3);
        return 0;
    }
    if (fn == (uint32_t)(uintptr_t)&isp_printf)
        return 0;
    if (fn == (uint32_t)(uintptr_t)&system_irq_func_set) {
        if (a1 == (uint32_t)(uintptr_t)&tiziano_adr_main_interrupt_static)
            a1 = (uint32_t)(uintptr_t)&adrlit_isr_cb;
        return (uint32_t)system_irq_func_set((int32_t)a0, (int32_t)a1);
    }
    if (fn == (uint32_t)(uintptr_t)&tisp_event_set_cb) {
        if (a2 == (uint32_t)(uintptr_t)&tisp_adr_main_process)
            a2 = (uint32_t)(uintptr_t)&adrlit_process_cb;
        return (uint32_t)tisp_event_set_cb((int32_t)a0, (int32_t)a1, (int32_t)a2);
    }
    if (fn == (uint32_t)(uintptr_t)&tisp_event_push)
        return (uint32_t)tisp_event_push(a0, (uintptr_t)a1);
    if (fn == (uint32_t)(uintptr_t)&__ashldi3) {
        uint64_t v = (((uint64_t)a1 << 32) | a0) << (a2 & 63);
        *v1 = (uint32_t)(v >> 32);
        return (uint32_t)v;
    }
    if (fn == (uint32_t)(uintptr_t)adrlit_lshrdi3_sym) {
        uint64_t v = (((uint64_t)a1 << 32) | a0) >> (a2 & 63);
        *v1 = (uint32_t)(v >> 32);
        return (uint32_t)v;
    }
    if (fn == (uint32_t)(uintptr_t)adrlit_div64_u64_sym) {
        uint64_t den = ((uint64_t)a3 << 32) | a2;
        uint64_t v = den ? adrlit_div64_u64(((uint64_t)a1 << 32) | a0, den) : 0;
        *v1 = (uint32_t)(v >> 32);
        return (uint32_t)v;
    }
    regtrace_adr_lit_bad_call++;
    regtrace_adr_lit_bad_target = fn;
    return 0;
}
''')
o.append('''/* one emulated MIPS stack per entry context; OEM frames nest to < 2 KiB */
#define ADRLIT_STACK 6144
static uint8_t adrlit_stack_init[ADRLIT_STACK] __attribute__((aligned(8)));
static uint8_t adrlit_stack_isr[ADRLIT_STACK] __attribute__((aligned(8)));
static uint8_t adrlit_stack_proc[ADRLIT_STACK] __attribute__((aligned(8)));
#define ADRLIT_SP(s) ((uint32_t)(uintptr_t)((s) + ADRLIT_STACK - 64))

static int32_t adrlit_isr_cb(void)
{
    regtrace_adr_lit_isr_count++;
    return tiziano_adr_main_interrupt_static_lit(0, 0, 0, 0, ADRLIT_SP(adrlit_stack_isr), NULL);
}

static int32_t adrlit_process_cb(uint32_t a0, uint32_t a1, uint32_t a2,
                                 uint32_t a3, uint32_t a4)
{
    (void)a4;
    regtrace_adr_lit_process_count++;
    return tisp_adr_main_process_lit(a0, a1, a2, a3, ADRLIT_SP(adrlit_stack_proc), NULL);
}
''')
o.append('\n'.join(d))
o.append('''
static int regtrace_adr_main_init_lit(uint32_t width, uint32_t height)
{
    int ret = (int)tisp_adr_main_init_lit(width, height, 0, 0,
                                          ADRLIT_SP(adrlit_stack_init), NULL);

    regtrace_adr_lit_init_ret = ret;
    regtrace_t40_adr_lit_active = !ret;
    printk(KERN_INFO "tx_isp_t40_recovered: adr-main-init-lit %ux%u ret=%d bad_call=%u\\n",
           width, height, ret, regtrace_adr_lit_bad_call);
    return ret;
}
''')
open(OUT, 'w').write('\n'.join(o))
print("private symbols:", len(priv), "functions:", len(fns))
