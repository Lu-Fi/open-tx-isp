#!/usr/bin/env python3
# gen_t40_defog_lit.py <workdir> <oem.ko> <objdump> <out.inc>
# Literal OEM defog chain (tisp_defog_*), same scheme as gen_t40_adr_lit.py:
#   <workdir>/prod.sym      objdump -t of the OEM module
#   <workdir>/defog/fnlist  functions to translate (one per line)
#   <workdir>/defog/<fn>.c  mips2c_literal.py output per function (CALL_DISPATCH, BSS_HI_ZERO, SYMTAB)
import sys, re, subprocess
W, KO, OD, OUT = sys.argv[1:5]
PFX = 'dfglit'
fns = open(f"{W}/defog/fnlist").read().split()
def cname(f):   # tisp_defog_get_data.part.0 -> tisp_defog_get_data_part_0 (asm label kept in the driver)
    return re.sub(r'[.$]', '_', f)
syms = {}
for l in open(f"{W}/prod.sym"):
    p = l.split()
    if len(p) >= 6 and p[2] == 'O' and p[3] in ('.bss', '.data', '.rodata'):
        syms[p[5]] = (p[3], int(p[0], 16), int(p[4], 16))
SHARED = {'tparamsN', 'tispinfo', 'tispSecdInfo', 'tisp_tattr'}
# .text tail call by HI16/LO16 pair (jr t9 to a local function): target by hand from the asm
TEXTFIX = {'tisp_defog_get_data': 'tisp_defog_get_data_part_0', 'tisp_defog_main_interrupt_static': 'tisp_defog_get_data_part_0'}
bodies = {}
used = set()
for f in fns:
    t = open(f"{W}/defog/{f}.c").read().split('\n')
    t = [l for l in t if not l.startswith('/*')]
    b = '\n'.join(t)
    for m in re.finditer(r'&([A-Za-z_$][A-Za-z_0-9$.]*)', b):
        used.add(m.group(1))
    bodies[f] = b
priv = sorted(s for s in used if s in syms and s not in SHARED)
def secbytes(sec):
    out = subprocess.run([OD, '-s', '-j', sec, KO], capture_output=True, text=True).stdout
    data = {}
    for l in out.split('\n'):
        m = re.match(r'\s*([0-9a-f]+) ((?:[0-9a-f]{2,8} ){1,4})', l)
        if not m: continue
        a = int(m.group(1), 16)
        hx = ''.join(m.group(2).split())
        for i in range(0, len(hx), 2):
            data[a + i // 2] = int(hx[i:i+2], 16)
    return data
secs = {s: secbytes(s) for s in ('.data', '.rodata')}
o = []
o.append('''/*
 * Literal mips2c defog chain (TOP bit 11) from the OEM sc830ai tx-isp-t40.ko:
 * tisp_defog_init (parameter refresh, register writers para1/2/3, IRQ 10 and
 * event 4 hooks), tisp_defog_main_interrupt_static (statistics read-out),
 * tisp_defog_main_process (Tiziano_defog_soft: transmission estimate,
 * strength interpolation, update_reg_para2), tisp_defog_dn_params_refresh,
 * tisp_s_defog_ratio and tisp_defog_deinit.  Generated by
 * tools/gen_t40_defog_lit.py with tools/mips2c_literal.py (runtime call
 * dispatch, full HI16/LO16 section addresses); 0 unhandled opcodes.
 *
 * Why: the recovered defog lift never hooks the block (the lifted init calls
 * the ISR function with (10, &isr) in place of system_irq_func_set and
 * tisp_event_set_cb with one argument), so defog stayed bypassed in every
 * profile although the sc830ai linear bank enables it (vendor TOP 0x7FD9004D
 * has bit 11 clear).  All defog state is private here (dfglit_*, OEM sizes,
 * OEM .data initial bytes); tparamsN, tispinfo, tispSecdInfo and tisp_tattr
 * are shared.  One emulated MIPS stack per entry context (init / ISR /
 * event / control).  Active only with t40_defog_on=1 and
 * t40_gates_oem_offset=1; TOP bit 11 is cleared only when the init returned 0.
 */
static bool regtrace_t40_defog_on = true;
module_param_named(t40_defog_on, regtrace_t40_defog_on, bool, 0644);
MODULE_PARM_DESC(t40_defog_on, "1 (with t40_gates_oem_offset=1) runs the literal OEM defog chain and clears TOP bit 11 after a successful init (default 1)");
static bool regtrace_t40_defog_lit_active;
static int regtrace_defog_lit_init_ret = -1;
static unsigned int regtrace_defog_lit_isr_count, regtrace_defog_lit_process_count;
static unsigned int regtrace_defog_lit_bad_call;
static uint32_t regtrace_defog_lit_bad_target;
module_param_named(dfglit_init_ret, regtrace_defog_lit_init_ret, int, 0444);
module_param_named(dfglit_isr_count, regtrace_defog_lit_isr_count, uint, 0444);
module_param_named(dfglit_process_count, regtrace_defog_lit_process_count, uint, 0444);
module_param_named(dfglit_bad_call, regtrace_defog_lit_bad_call, uint, 0444);
module_param_named(dfglit_bad_target, regtrace_defog_lit_bad_target, uint, 0444);

extern char dfglit_ashrdi3_sym[] __asm__("__ashrdi3");
static const char dfglit_str[] = "defog";
''')
for s in priv:
    sec, a, z = syms[s]
    if sec == '.bss':
        o.append(f"static uint8_t {PFX}_{cname(s)}[{max(z,1)}] __attribute__((aligned(8)));")
    else:
        b = secs[sec]
        vals = ', '.join(f"0x{b.get(a+i,0):02x}" for i in range(z))
        o.append(f"static uint8_t {PFX}_{cname(s)}[{max(z,1)}] __attribute__((aligned(8))) = {{ {vals} }};")
anon = sorted({int(m, 16) for b in bodies.values()
               for m in re.findall(r'/\*UNMAPPED \.rodata\+0x([0-9a-f]+)\*/0', b)})
ro_starts = sorted(a for (sec, a, z) in syms.values() if sec == '.rodata')
for i, a in enumerate(anon):
    nxt = [x for x in ro_starts if x > a] + ([anon[i+1]] if i + 1 < len(anon) else [])
    z = min(min(nxt) - a if nxt else 256, 1024)
    b = secs['.rodata']
    vals = ', '.join(f"0x{b.get(a+k,0):02x}" for k in range(z))
    o.append(f"static const uint8_t {PFX}_ro_{a:x}[{z}] __attribute__((aligned(8))) = {{ {vals} }};")
o.append('')
for f in fns:
    o.append(f"static int32_t {cname(f)}_lit(uint32_t a0_in, uint32_t a1_in, uint32_t a2_in, uint32_t a3_in, uint32_t sp_in, uint32_t *v1_io, uint32_t v0_in);")
o.append(f"static uint32_t {PFX}_dispatch(uint32_t fn, uint32_t a0, uint32_t a1, uint32_t a2, uint32_t a3, uint32_t sp, uint32_t *v1, uint32_t v0);")
o.append(f"#define DFG_DISPATCH(r) {PFX}_dispatch((r), r_a0, r_a1, r_a2, r_a3, r_sp, &r_v1, r_v0)")
o.append('')
def fix(f, b):
    b = b.replace('ADR_DISPATCH', 'DFG_DISPATCH')
    b = re.sub(r'/\*UNMAPPED \.rodata\+0x([0-9a-f]+)\*/0', lambda m: f'{PFX}_ro_{m.group(1)}', b)
    b = re.sub(r'&\$LC\d+', f'{PFX}_str', b)
    b = b.replace('&__ashrdi3', f'{PFX}_ashrdi3_sym')
    if f in TEXTFIX:
        b = b.replace('&.text', '&' + TEXTFIX[f])
    def rp(m):
        n = m.group(1)
        if n in priv: return f'{PFX}_{cname(n)}'
        if n in fns and n != cname(n): return '&' + cname(n)
        return m.group(0)
    return re.sub(r'&([A-Za-z_][A-Za-z_0-9.]*)', rp, b)
for f in fns:
    o.append(f'''static int32_t {cname(f)}_lit(uint32_t a0_in, uint32_t a1_in, uint32_t a2_in, uint32_t a3_in, uint32_t sp_in, uint32_t *v1_io, uint32_t v0_in)
{{
    uint32_t r_v0 = v0_in, r_v1 = v1_io ? *v1_io : 0;
    uint32_t r_t0 = 0, r_t1 = 0, r_t2 = 0, r_t3 = 0, r_t4 = 0, r_t5 = 0;
    uint32_t r_t6 = 0, r_t7 = 0, r_t8 = 0, r_t9 = 0;
    uint32_t r_s0 = 0, r_s1 = 0, r_s2 = 0, r_s3 = 0, r_s4 = 0, r_s5 = 0;
    uint32_t r_s6 = 0, r_s7 = 0, r_s8 = 0, r_ra = 0, r_at = 0;
    uint32_t mips_lo = 0, mips_hi = 0, mips_cond = 0;
    uint32_t r_a0 = a0_in, r_a1 = a1_in, r_a2 = a2_in, r_a3 = a3_in;
    uint32_t r_sp = sp_in;

    (void)r_at; (void)r_ra; (void)r_t8; (void)r_t9; (void)mips_lo; (void)mips_hi;
    (void)mips_cond;
{fix(f, bodies[f])}
fn_exit:
    if (v1_io)
        *v1_io = r_v1;
    return (int32_t)r_v0;
}}
''')
d = [f'''static uint32_t {PFX}_dispatch(uint32_t fn, uint32_t a0, uint32_t a1, uint32_t a2, uint32_t a3, uint32_t sp, uint32_t *v1, uint32_t v0)
{{''']
for f in fns:
    d.append(f"    if (fn == (uint32_t)(uintptr_t)&{cname(f)})\n        return (uint32_t){cname(f)}_lit(a0, a1, a2, a3, sp, v1, v0);")
d.append(f'''    if (fn == (uint32_t)(uintptr_t)&system_reg_write)
        return (uint32_t)system_reg_write(a0, a1);
    if (fn == (uint32_t)(uintptr_t)&system_reg_read)
        return (uint32_t)system_reg_read(a0);
    if (fn == (uint32_t)(uintptr_t)&memcpy)
        return (uint32_t)(uintptr_t)memcpy((void *)(uintptr_t)a0, (const void *)(uintptr_t)a1, a2);
    if (fn == (uint32_t)(uintptr_t)&memset)
        return (uint32_t)(uintptr_t)memset((void *)(uintptr_t)a0, (int)a1, a2);
    if (fn == (uint32_t)(uintptr_t)&private_kmalloc)
        return (uint32_t)(uintptr_t)kmalloc(a0, (gfp_t)a1);
    if (fn == (uint32_t)(uintptr_t)&kmem_cache_alloc)
        return (uint32_t)(uintptr_t)kmem_cache_alloc((struct kmem_cache *)(uintptr_t)a0, (gfp_t)a1);
    if (fn == (uint32_t)(uintptr_t)&private_kfree || fn == (uint32_t)(uintptr_t)&kfree) {{
        kfree((void *)(uintptr_t)a0);
        return 0;
    }}
    if (fn == (uint32_t)(uintptr_t)&private_dma_cache_sync) {{
        if (a1 && a2)
            dma_cache_sync((void *)(uintptr_t)a0, (void *)(uintptr_t)a1, a2, (enum dma_data_direction)a3);
        return 0;
    }}
    if (fn == (uint32_t)(uintptr_t)&tisp_get_tuning)
        return (uint32_t)tisp_get_tuning();
    if (fn == (uint32_t)(uintptr_t)&system_irq_func_set) {{
        if (a1 == (uint32_t)(uintptr_t)&tisp_defog_main_interrupt_static)
            a1 = (uint32_t)(uintptr_t)&{PFX}_isr_cb;
        return (uint32_t)system_irq_func_set((int32_t)a0, (int32_t)a1);
    }}
    if (fn == (uint32_t)(uintptr_t)&tisp_event_set_cb) {{
        if (a2 == (uint32_t)(uintptr_t)&tisp_defog_main_process)
            a2 = (uint32_t)(uintptr_t)&{PFX}_process_cb;
        return (uint32_t)tisp_event_set_cb((int32_t)a0, (int32_t)a1, (int32_t)a2);
    }}
    if (fn == (uint32_t)(uintptr_t)&tisp_event_push)
        return (uint32_t)tisp_event_push(a0, (uintptr_t)a1);
    if (fn == (uint32_t)(uintptr_t){PFX}_ashrdi3_sym) {{
        int64_t v = (int64_t)(((uint64_t)a1 << 32) | a0) >> (a2 & 63);
        *v1 = (uint32_t)((uint64_t)v >> 32);
        return (uint32_t)v;
    }}
    regtrace_defog_lit_bad_call++;
    regtrace_defog_lit_bad_target = fn;
    return 0;
}}
''')
o.append(f'''/* one emulated MIPS stack per entry context */
#define DFGLIT_STACK 6144
static uint8_t {PFX}_stack_init[DFGLIT_STACK] __attribute__((aligned(8)));
static uint8_t {PFX}_stack_isr[DFGLIT_STACK] __attribute__((aligned(8)));
static uint8_t {PFX}_stack_proc[DFGLIT_STACK] __attribute__((aligned(8)));
static uint8_t {PFX}_stack_ctl[DFGLIT_STACK] __attribute__((aligned(8)));
#define DFGLIT_SP(s) ((uint32_t)(uintptr_t)((s) + DFGLIT_STACK - 64))

static int32_t {PFX}_isr_cb(void)
{{
    regtrace_defog_lit_isr_count++;
    return tisp_defog_main_interrupt_static_lit(0, 0, 0, 0, DFGLIT_SP({PFX}_stack_isr), NULL, 0);
}}

static int32_t {PFX}_process_cb(uint32_t a0, uint32_t a1, uint32_t a2,
                                 uint32_t a3, uint32_t a4)
{{
    (void)a4;
    regtrace_defog_lit_process_count++;
    return tisp_defog_main_process_lit(a0, a1, a2, a3, DFGLIT_SP({PFX}_stack_proc), NULL, 0);
}}
''')
o.append('\n'.join(d))
o.append(f'''
/* OEM tisp_day_or_night_s_ctrl -> tisp_defog_dn_params_refresh(sensor, width, height) */
static int regtrace_defog_dn_refresh_lit(uint32_t width, uint32_t height)
{{
    if (!regtrace_t40_defog_lit_active)
        return 0;
    return (int)tisp_defog_dn_params_refresh_lit(0, width, height, 0,
                                                 DFGLIT_SP({PFX}_stack_ctl), NULL, 0);
}}

/* module exit, after the event threads stopped: unhook IRQ 10 / event 4, free the OEM buffers */
static void regtrace_defog_lit_cleanup(void)
{{
    if (!regtrace_t40_defog_lit_active)
        return;
    regtrace_t40_defog_lit_active = false;
    system_irq_func_set(10, 0);
    tisp_event_set_cb(0, 4, 0);
    (void)tisp_defog_deinit_lit(0, 0, 0, 0, DFGLIT_SP({PFX}_stack_ctl), NULL, 0);
    printk(KERN_INFO "tx_isp_t40_recovered: defog-lit deinit done\\n");
}}

/* OEM tisp_main_long_ev_update -> tisp_defog_ev_update(sensor, -, ev_lo, ev_hi): ev = IT x gain (Q10), stored >> 10 */
static void regtrace_defog_ev_update_lit(uint64_t ev_q10)
{{
    if (!regtrace_t40_defog_lit_active)
        return;
    (void)tisp_defog_ev_update_lit(0, 0, (uint32_t)ev_q10, (uint32_t)(ev_q10 >> 32),
                                   DFGLIT_SP({PFX}_stack_ctl), NULL, 0);
}}

/* SetModule_Ratio (defog): OEM tisp_s_defog_ratio(sensor) on the private defog state
 * (tattr +864 enable / +868 ratio), strength interpolation + register update. */
static int regtrace_defog_ratio_lit(void)
{{
    if (!regtrace_t40_defog_lit_active)
        return -ENODEV;
    return (int)tisp_s_defog_ratio_lit(0, 0, 0, 0, DFGLIT_SP({PFX}_stack_ctl), NULL, 0);
}}

static int regtrace_defog_init_lit(uint32_t width, uint32_t height)
{{
    int ret = (int)tisp_defog_init_lit(0, width, height, 0,
                                       DFGLIT_SP({PFX}_stack_init), NULL, 0);

    regtrace_defog_lit_init_ret = ret;
    regtrace_t40_defog_lit_active = !ret;
    printk(KERN_INFO "tx_isp_t40_recovered: defog-main-init-lit %ux%u ret=%d bad_call=%u\\n",
           width, height, ret, regtrace_defog_lit_bad_call);
    return ret;
}}
''')
open(OUT, 'w').write('\n'.join(o))
print("private symbols:", len(priv), "functions:", len(fns))
