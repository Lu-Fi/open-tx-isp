#!/usr/bin/env python3
# gen_t40_lce_lit.py <workdir> <oem.ko> <objdump> <out.inc>
# Literal OEM defog chain (tisp_defog_*), same scheme as gen_t40_adr_lit.py:
#   <workdir>/prod.sym      objdump -t of the OEM module
#   <workdir>/defog/fnlist  functions to translate (one per line)
#   <workdir>/defog/<fn>.c  mips2c_literal.py output per function (CALL_DISPATCH, BSS_HI_ZERO, SYMTAB)
import sys, re, subprocess
W, KO, OD, OUT = sys.argv[1:5]
PFX = 'lcelit'
fns = open(f"{W}/lce/fnlist").read().split()
def cname(f):   # tisp_defog_get_data.part.0 -> tisp_defog_get_data_part_0 (asm label kept in the driver)
    return re.sub(r'[.$]', '_', f)
syms = {}
for l in open(f"{W}/prod.sym"):
    p = l.split()
    if len(p) >= 6 and p[2] == 'O' and p[3] in ('.bss', '.data', '.rodata'):
        syms[p[5]] = (p[3], int(p[0], 16), int(p[4], 16))
SHARED = {'tparamsN', 'tispinfo', 'tispSecdInfo', 'tisp_tattr', 'wdr_lce_para'}
# .text tail call by HI16/LO16 pair (jr t9 to a local function): target by hand from the asm
TEXTFIX = {}
bodies = {}
used = set()
for f in fns:
    t = open(f"{W}/lce/{f}.c").read().split('\n')
    t = [l for l in t if not l.startswith('/*')]
    b = '\n'.join(t)
    for m in re.finditer(r'&([A-Za-z_$][A-Za-z_0-9$.]*)', b):
        used.add(m.group(1))
    bodies[f] = b
priv = sorted(s for s in used if s in syms and s not in SHARED)
def secbytes(sec):
    out = subprocess.run([OD, '-s', '-j', sec, KO], capture_output=True, text=True).stdout
    data = {}
    for l in out.split('\n'):
        m = re.match(r'\s*([0-9a-f]+) ((?:[0-9a-f]{2,8} ){1,4})', l)
        if not m: continue
        a = int(m.group(1), 16)
        hx = ''.join(m.group(2).split())
        for i in range(0, len(hx), 2):
            data[a + i // 2] = int(hx[i:i+2], 16)
    return data
secs = {s: secbytes(s) for s in ('.data', '.rodata')}
o = []
o.append('''/*
 * Literal mips2c LCE chain (local contrast enhancement, TOP bit 21) from the
 * OEM sc830ai tx-isp-t40.ko: tisp_lce_init (curves, awdr/tool parameter
 * conversion, write_all_reg, IRQ 8 / event 0x10 hooks), the statistics ISR,
 * tisp_lce_main_process (Tisp_lce_soft: histogram method, light lock,
 * pdf->cdf, draw_lines), tisp_lce_tgain_update, tisp_lce_dn_params_refresh
 * and tisp_lce_deinit.  Generated by tools/gen_t40_lce_lit.py with
 * tools/mips2c_literal.py; 0 unhandled opcodes.
 *
 * Why: TOP bit 21 was never released by the recovered driver (the lifted LCE
 * chain is fragmentary), while the sc830ai linear bank enables LCE (vendor TOP
 * 0x7FD9004D).  All LCE state is private here (lcelit_*); tparamsN and
 * wdr_lce_para are shared.  Active only with t40_lce_on=1 and
 * t40_gates_oem_offset=1; TOP bit 21 is cleared only when the init returned 0.
 */
static bool regtrace_t40_lce_on = true;
module_param_named(t40_lce_on, regtrace_t40_lce_on, bool, 0644);
MODULE_PARM_DESC(t40_lce_on, "1 (with t40_gates_oem_offset=1) runs the literal OEM LCE chain and clears TOP bit 21 after a successful init (default 1)");
static bool regtrace_t40_lce_lit_active;
static int regtrace_lce_lit_init_ret = -1;
static unsigned int regtrace_lce_lit_isr_count, regtrace_lce_lit_process_count;
static unsigned int regtrace_lce_lit_bad_call;
static uint32_t regtrace_lce_lit_bad_target;
module_param_named(lcelit_init_ret, regtrace_lce_lit_init_ret, int, 0444);
module_param_named(lcelit_isr_count, regtrace_lce_lit_isr_count, uint, 0444);
module_param_named(lcelit_process_count, regtrace_lce_lit_process_count, uint, 0444);
module_param_named(lcelit_bad_call, regtrace_lce_lit_bad_call, uint, 0444);
module_param_named(lcelit_bad_target, regtrace_lce_lit_bad_target, uint, 0444);

extern char lcelit_lshrdi3_sym[] __asm__("__lshrdi3");
static const char lcelit_str[] = "lce";
''')
for s in priv:
    sec, a, z = syms[s]
    if sec == '.bss':
        o.append(f"static uint8_t {PFX}_{cname(s)}[{max(z,1)}] __attribute__((aligned(8)));")
    else:
        b = secs[sec]
        vals = ', '.join(f"0x{b.get(a+i,0):02x}" for i in range(z))
        o.append(f"static uint8_t {PFX}_{cname(s)}[{max(z,1)}] __attribute__((aligned(8))) = {{ {vals} }};")
anon = sorted({int(m, 16) for b in bodies.values()
               for m in re.findall(r'/\*UNMAPPED \.rodata\+0x([0-9a-f]+)\*/0', b)})
ro_starts = sorted(a for (sec, a, z) in syms.values() if sec == '.rodata')
for i, a in enumerate(anon):
    nxt = [x for x in ro_starts if x > a] + ([anon[i+1]] if i + 1 < len(anon) else [])
    z = min(min(nxt) - a if nxt else 256, 1024)
    b = secs['.rodata']
    vals = ', '.join(f"0x{b.get(a+k,0):02x}" for k in range(z))
    o.append(f"static const uint8_t {PFX}_ro_{a:x}[{z}] __attribute__((aligned(8))) = {{ {vals} }};")
o.append('')
for f in fns:
    o.append(f"static int32_t {cname(f)}_lit(uint32_t a0_in, uint32_t a1_in, uint32_t a2_in, uint32_t a3_in, uint32_t sp_in, uint32_t *v1_io, uint32_t v0_in);")
o.append(f"static uint32_t {PFX}_dispatch(uint32_t fn, uint32_t a0, uint32_t a1, uint32_t a2, uint32_t a3, uint32_t sp, uint32_t *v1, uint32_t v0);")
o.append(f"#define LCE_DISPATCH(r) {PFX}_dispatch((r), r_a0, r_a1, r_a2, r_a3, r_sp, &r_v1, r_v0)")
o.append('')
def fix(f, b):
    b = b.replace('ADR_DISPATCH', 'LCE_DISPATCH')
    b = re.sub(r'/\*UNMAPPED \.rodata\+0x([0-9a-f]+)\*/0', lambda m: f'{PFX}_ro_{m.group(1)}', b)
    b = re.sub(r'&\$LC\d+', f'{PFX}_str', b)
    b = b.replace('&__lshrdi3', f'{PFX}_lshrdi3_sym')
    if f in TEXTFIX:
        b = b.replace('&.text', '&' + TEXTFIX[f])
    def rp(m):
        n = m.group(1)
        if n in priv: return f'{PFX}_{cname(n)}'
        if n in fns and n != cname(n): return '&' + cname(n)
        return m.group(0)
    return re.sub(r'&([A-Za-z_][A-Za-z_0-9.]*)', rp, b)
for f in fns:
    o.append(f'''static int32_t {cname(f)}_lit(uint32_t a0_in, uint32_t a1_in, uint32_t a2_in, uint32_t a3_in, uint32_t sp_in, uint32_t *v1_io, uint32_t v0_in)
{{
    uint32_t r_v0 = v0_in, r_v1 = v1_io ? *v1_io : 0;
    uint32_t r_t0 = 0, r_t1 = 0, r_t2 = 0, r_t3 = 0, r_t4 = 0, r_t5 = 0;
    uint32_t r_t6 = 0, r_t7 = 0, r_t8 = 0, r_t9 = 0;
    uint32_t r_s0 = 0, r_s1 = 0, r_s2 = 0, r_s3 = 0, r_s4 = 0, r_s5 = 0;
    uint32_t r_s6 = 0, r_s7 = 0, r_s8 = 0, r_ra = 0, r_at = 0;
    uint32_t mips_lo = 0, mips_hi = 0, mips_cond = 0;
    uint32_t r_a0 = a0_in, r_a1 = a1_in, r_a2 = a2_in, r_a3 = a3_in;
    uint32_t r_sp = sp_in;

    (void)r_at; (void)r_ra; (void)r_t8; (void)r_t9; (void)mips_lo; (void)mips_hi;
    (void)mips_cond;
{fix(f, bodies[f])}
fn_exit:
    if (v1_io)
        *v1_io = r_v1;
    return (int32_t)r_v0;
}}
''')
d = [f'''static uint32_t {PFX}_dispatch(uint32_t fn, uint32_t a0, uint32_t a1, uint32_t a2, uint32_t a3, uint32_t sp, uint32_t *v1, uint32_t v0)
{{''']
for f in fns:
    d.append(f"    if (fn == (uint32_t)(uintptr_t)&{cname(f)})\n        return (uint32_t){cname(f)}_lit(a0, a1, a2, a3, sp, v1, v0);")
d.append(f'''    if (fn == (uint32_t)(uintptr_t)&system_reg_write)
        return (uint32_t)system_reg_write(a0, a1);
    if (fn == (uint32_t)(uintptr_t)&system_reg_read)
        return (uint32_t)system_reg_read(a0);
    if (fn == (uint32_t)(uintptr_t)&memcpy)
        return (uint32_t)(uintptr_t)memcpy((void *)(uintptr_t)a0, (const void *)(uintptr_t)a1, a2);
    if (fn == (uint32_t)(uintptr_t)&memset)
        return (uint32_t)(uintptr_t)memset((void *)(uintptr_t)a0, (int)a1, a2);
    if (fn == (uint32_t)(uintptr_t)&private_vmalloc)
        return (uint32_t)(uintptr_t)vmalloc(a0);
    if (fn == (uint32_t)(uintptr_t)&private_vfree) {{
        vfree((void *)(uintptr_t)a0);
        return 0;
    }}
    if (fn == (uint32_t)(uintptr_t)&isp_printf)
        return 0;
    if (fn == (uint32_t)(uintptr_t)&system_irq_func_set) {{
        if (a1 == (uint32_t)(uintptr_t)&tisp_lce_main_interrupt_static)
            a1 = (uint32_t)(uintptr_t)&{PFX}_isr_cb;
        return (uint32_t)system_irq_func_set((int32_t)a0, (int32_t)a1);
    }}
    if (fn == (uint32_t)(uintptr_t)&tisp_event_set_cb) {{
        if (a2 == (uint32_t)(uintptr_t)&tisp_lce_main_process)
            a2 = (uint32_t)(uintptr_t)&{PFX}_process_cb;
        return (uint32_t)tisp_event_set_cb((int32_t)a0, (int32_t)a1, (int32_t)a2);
    }}
    if (fn == (uint32_t)(uintptr_t)&tisp_event_push)
        return (uint32_t)tisp_event_push(a0, (uintptr_t)a1);
    if (fn == (uint32_t)(uintptr_t){PFX}_lshrdi3_sym) {{
        uint64_t v = (((uint64_t)a1 << 32) | a0) >> (a2 & 63);
        *v1 = (uint32_t)(v >> 32);
        return (uint32_t)v;
    }}
    regtrace_lce_lit_bad_call++;
    regtrace_lce_lit_bad_target = fn;
    return 0;
}}
''')
o.append(f'''/* one emulated MIPS stack per entry context */
#define LCELIT_STACK 6144
static uint8_t {PFX}_stack_init[LCELIT_STACK] __attribute__((aligned(8)));
static uint8_t {PFX}_stack_isr[LCELIT_STACK] __attribute__((aligned(8)));
static uint8_t {PFX}_stack_proc[LCELIT_STACK] __attribute__((aligned(8)));
static uint8_t {PFX}_stack_ctl[LCELIT_STACK] __attribute__((aligned(8)));
#define LCELIT_SP(s) ((uint32_t)(uintptr_t)((s) + LCELIT_STACK - 64))

static int32_t {PFX}_isr_cb(void)
{{
    regtrace_lce_lit_isr_count++;
    return tisp_lce_main_interrupt_static_lit(0, 0, 0, 0, LCELIT_SP({PFX}_stack_isr), NULL, 0);
}}

static int32_t {PFX}_process_cb(uint32_t a0, uint32_t a1, uint32_t a2,
                                 uint32_t a3, uint32_t a4)
{{
    (void)a4;
    regtrace_lce_lit_process_count++;
    return tisp_lce_main_process_lit(a0, a1, a2, a3, LCELIT_SP({PFX}_stack_proc), NULL, 0);
}}
''')
o.append('\n'.join(d))
o.append(f'''
/* OEM tisp_day_or_night_s_ctrl -> tisp_lce_dn_params_refresh(sensor) */
static int regtrace_lce_dn_refresh_lit(void)
{{
    if (!regtrace_t40_lce_lit_active)
        return 0;
    return (int)tisp_lce_dn_params_refresh_lit(0, 0, 0, 0, LCELIT_SP({PFX}_stack_ctl), NULL, 0);
}}

/* OEM tisp_main_long_tgain_update -> tisp_lce_tgain_update(sensor, tgain 16.16 log2) */
static void regtrace_lce_tgain_update_lit(uint32_t tgain)
{{
    if (!regtrace_t40_lce_lit_active)
        return;
    (void)tisp_lce_tgain_update_lit(0, tgain, 0, 0, LCELIT_SP({PFX}_stack_ctl), NULL, 0);
}}

/* module exit, after the event threads stopped: unhook IRQ 8 / event 0x10, free the OEM buffers */
static void regtrace_lce_lit_cleanup(void)
{{
    if (!regtrace_t40_lce_lit_active)
        return;
    regtrace_t40_lce_lit_active = false;
    system_irq_func_set(8, 0);
    tisp_event_set_cb(0, 0x10, 0);
    (void)tisp_lce_deinit_lit(0, 0, 0, 0, LCELIT_SP({PFX}_stack_ctl), NULL, 0);
    printk(KERN_INFO "tx_isp_t40_recovered: lce-lit deinit done\\n");
}}

/* OEM tisp_main_init: tisp_lce_init(sensor, width, height, sensor_total_num) */
static int regtrace_lce_init_lit(uint32_t width, uint32_t height)
{{
    int ret = (int)tisp_lce_init_lit(0, width, height, 1,
                                     LCELIT_SP({PFX}_stack_init), NULL, 0);

    regtrace_lce_lit_init_ret = ret;
    regtrace_t40_lce_lit_active = !ret;
    printk(KERN_INFO "tx_isp_t40_recovered: lce-main-init-lit %ux%u ret=%d bad_call=%u\\n",
           width, height, ret, regtrace_lce_lit_bad_call);
    return ret;
}}
''')
open(OUT, 'w').write('\n'.join(o))
print("private symbols:", len(priv), "functions:", len(fns))
