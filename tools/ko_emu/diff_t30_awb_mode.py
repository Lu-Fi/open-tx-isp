#!/usr/bin/env python3
"""diff_t30_awb_mode.py VENDOR.ko [--header OUT.h]: T30 AWB mode / scene presets (Lu-Fi/openimp#202).

Runs the SDK-built tx-isp-t30.ko (4ea12e1f) get_awb_idx (0x21a08) and awb_mode (0x21a30, the
apical_command(3, 0x60 AWB_MODE_ID, mode) set path) in Unicorn.  _GET_MOD_ENTRY16_PTR(255) returns a
synthetic 8-row table (distinct u16 per cell, no vendor data); AWB_fsm_process_state is a stub.
For every mode 0x28..0x48 it records the return value, stab[0x0c], stab[0x31], stab[0x32],
awb+0x75a and awb+0xec8; for get_awb_idx every input -64..191.  --header writes them as C tables for
tests/t30_awb_preset_host_test.c, which runs driver/t30/tx_isp_t30_awb_preset.h on the same inputs.
"""
import sys, struct, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from ko_emu import KoEmu

# synthetic table 255: 8 rows x 2 u16 (row r: 1000 + 16 r, 2000 + 16 r + 3); the host test uses the same
LUT = [(1000 + 16 * r, 2000 + 16 * r + 3) for r in range(8)]

def main():
    ko = sys.argv[1]
    out = sys.argv[sys.argv.index("--header") + 1] if "--header" in sys.argv else None
    st = {'lut': 0, 'arg': None, 'fsm': 0}
    def lut(e):
        from unicorn.mips_const import UC_MIPS_REG_A0
        st['arg'] = e.get_reg(UC_MIPS_REG_A0); return st['lut']
    def fsm(e): st['fsm'] += 1; return 0
    hle = {"_GET_MOD_ENTRY16_PTR": lut, "AWB_fsm_process_state": fsm, "printk": lambda e: 0}
    e = KoEmu(ko, hle=hle, max_insns=20000)
    for n in hle:
        if n in e.symaddr: e.stubname[e.symaddr[n]] = n
    stab = e.symaddr["stab"]
    st['lut'] = e.alloc(64, b"".join(struct.pack("<HH", a, b) for a, b in LUT))
    awb = e.alloc(0x1000); outp = e.alloc(4)
    idx = []
    for a in range(-64, 192):
        r = e.call("get_awb_idx", a & 0xffffffff)
        if r.stop: print("STOP get_awb_idx(%d): %s" % (a, r.stop)); sys.exit(1)
        idx.append((a, r.v0))
    rows = []
    for m in range(0x28, 0x49):
        e.write(stab, bytes(0x3c))
        e.write(stab + 0x31, b"\x5a\xa5")
        e.write(awb, bytes(0x1000))
        e.write(awb + 0x75a, b"\x77")
        e.write(awb + 0xec8, struct.pack("<I", 0x1234))
        st['arg'] = None; st['fsm'] = 0
        r = e.call("awb_mode", awb, m, 0, outp)
        if r.stop: print("STOP awb_mode(%#x): %s" % (m, r.stop)); sys.exit(1)
        s = e.read(stab, 0x3c)
        rows.append((m, r.v0, s[0x0c], s[0x31], s[0x32], e.read(awb + 0x75a, 1)[0],
                     struct.unpack("<I", e.read(awb + 0xec8, 4))[0], st['fsm'],
                     -1 if st['arg'] is None else st['arg']))
    for m in rows:
        if 0x34 <= m[0] <= 0x3a: print("mode %#x -> ret %d r %d b %d (table %d)" % (m[0], m[1], m[3], m[4], m[8]))
    print("get_awb_idx: %d inputs, awb_mode: %d modes" % (len(idx), len(rows)))
    if out:
        with open(out, "w") as f:
            f.write("/* generated by tools/ko_emu/diff_t30_awb_mode.py from the SDK-built tx-isp-t30.ko 4ea12e1f\n"
                    " * get_awb_idx 0x21a08: { input, return } */\n")
            f.write("static const int t30_vendor_awb_idx[][2] = {\n")
            for a, v in idx: f.write("\t{ %d, %d },\n" % (a, v))
            f.write("};\n/* awb_mode 0x21a30 (set, arg3 = 0) with table 255 = T30_AWB_TEST_LUT, stab[0x31..0x32] = 0x5a/0xa5,\n"
                    " * awb+0x75a = 0x77, awb+0xec8 = 0x1234 before the call:\n"
                    " * { mode, ret, stab[0x0c], stab[0x31], stab[0x32], awb+0x75a, awb+0xec8, fsm calls, table id or -1 } */\n")
            f.write("static const int t30_vendor_awb_mode[][9] = {\n")
            for m in rows: f.write("\t{ %s },\n" % ", ".join("%#x" % v if i in (0, 6) else str(v) for i, v in enumerate(m)))
            f.write("};\n")
    sys.exit(0)

main()
