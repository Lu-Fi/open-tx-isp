#!/usr/bin/env python3
"""diff_t30_ae_init.py VENDOR.ko [--header OUT.h]: T30 AE inputs at ISP init (Lu-Fi/openimp#338).

Runs the SDK-built tx-isp-t30.ko (4ea12e1f) AE_fsm_clear (0x2de80) and cmos_fsm_clear (0x2d810) in
Unicorn on contexts filled with a byte pattern and records every byte afterwards (what they write and
what they leave), then adjust_exposure (0x29250) on random contexts: the eight frame exposure sets
(cmos_get_frame_exposure_set, modelled as a table of eight words), the AE accumulator update of
ae_exposure_correction (k = HDR table 146 word 0) and the cmos_set_exposure_target / raise_event
arguments.  log2_fixed_to_fixed is the model of tests/t30_ae_balanced_host_test.sh; no vendor data is
used.  tests/t30_ae_init_host_test.sh runs our C on the same inputs.
"""
import sys, random, struct, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from ko_emu import KoEmu
from unicorn.mips_const import UC_MIPS_REG_A0, UC_MIPS_REG_A1, UC_MIPS_REG_A2

M32 = 0xffffffff
def s32(x): x &= M32; return x - (1 << 32) if x >> 31 else x
def mlog2(x, fin, fout):
    x &= M32
    if x == 0: return 0
    msb = x.bit_length() - 1
    frac = ((x << (31 - msb)) & 0x7fffffff) >> (31 - fout)
    return s32(((msb - fin) << fout) + frac)
def pattern(n, salt): return bytes(((i * 7 + salt) & 0xff) for i in range(n))

AE_SIZE, CMOS_SIZE, ISP_SIZE = 0x440, 0x200, 0x400


def main():
    ko = sys.argv[1]
    out = sys.argv[sys.argv.index("--header") + 1] if "--header" in sys.argv else None
    st = {}
    a = lambda e, r: e.get_reg(r)
    def sets(e):
        i = a(e, UC_MIPS_REG_A1)
        if a(e, UC_MIPS_REG_A0) != st['isp'] + 280 or i > 7: raise RuntimeError("frame set %d" % i)
        return st['sets'] + 4 * i
    def uptr(e):
        if a(e, UC_MIPS_REG_A0) == 146 * 16 + st['mode']: return st['lut']
        raise RuntimeError("_GET_UINT_PTR(%d)" % a(e, UC_MIPS_REG_A0))
    def cap(e): st['cap'] = (a(e, UC_MIPS_REG_A0) - st['isp'], s32(a(e, UC_MIPS_REG_A1)), s32(a(e, UC_MIPS_REG_A2))); return 0
    def ev(e): st['ev'] = (a(e, UC_MIPS_REG_A0) - st['isp'], a(e, UC_MIPS_REG_A1)); return 0
    hle = {"log2_fixed_to_fixed": lambda e: mlog2(a(e, UC_MIPS_REG_A0), s32(a(e, UC_MIPS_REG_A1)), a(e, UC_MIPS_REG_A2) & 0xff) & M32,
           "cmos_get_frame_exposure_set": sets, "_GET_HDR_TABLE_INDEX": lambda e: (a(e, UC_MIPS_REG_A0) * 16 + a(e, UC_MIPS_REG_A1)) & M32,
           "_GET_UINT_PTR": uptr, "cmos_set_exposure_target": cap, "apical_fw_raise_event": ev, "printk": lambda e: 0}
    e = KoEmu(ko, hle=hle, max_insns=200000)
    for n in hle:
        if n in e.symaddr: e.stubname[e.symaddr[n]] = n
    blk = e.alloc(0x1000)
    e.write(blk, pattern(AE_SIZE, 0x5a))
    r = e.call("AE_fsm_clear", blk)
    if r.stop: print("STOP AE_fsm_clear: %s" % r.stop); sys.exit(1)
    ae_after = e.read(blk, AE_SIZE)
    e.write(blk, pattern(CMOS_SIZE, 0x33))
    r = e.call("cmos_fsm_clear", blk)
    if r.stop: print("STOP cmos_fsm_clear: %s" % r.stop); sys.exit(1)
    cmos_after = e.read(blk, CMOS_SIZE)
    st['isp'] = e.alloc(0x1600); st['sets'] = e.alloc(32); st['lut'] = e.alloc(16)
    rnd = random.Random(338); rows = []
    for k in range(200):
        c = {'mode': rnd.choice([0, 0, 1, 2]), 'k': rnd.choice([1, 2, 16, rnd.randrange(1, 1 << 16)]),
             'step': rnd.choice([0, rnd.randrange(-(1 << 20), 1 << 20), rnd.randrange(-(1 << 31), 1 << 31)]),
             'sets': [rnd.choice([0, rnd.randrange(0, 1 << 20), rnd.randrange(-(1 << 31), 1 << 31)]) for _ in range(8)],
             'acc': rnd.choice([0, rnd.randrange(0, 1 << 40), rnd.randrange(0, 1 << 64)]),
             'w334': rnd.randrange(-(1 << 31), 1 << 31), 'w348': rnd.randrange(-(1 << 31), 1 << 31)}
        st['mode'] = c['mode']; st['cap'] = st['ev'] = None
        isp = st['isp']
        e.write(isp, bytes(0x1600)); e.write(isp + 5412 + 0x18, bytes([c['mode']]))
        e.write(isp + 0x320, struct.pack("<I", isp + 0x18))          # AE context word 0: the FSM manager
        e.write(isp + 0x320 + 24, struct.pack("<Q", c['acc']))
        e.write(isp + 820, struct.pack("<i", c['w334'])); e.write(isp + 840, struct.pack("<i", c['w348']))
        e.write(st['sets'], struct.pack("<8i", *c['sets'])); e.write(st['lut'], struct.pack("<4I", c['k'], 0, 0, 0))
        r = e.call("adjust_exposure", isp, c['step'])
        if r.stop or st['cap'] is None or st['ev'] is None: print("STOP adjust_exposure %d: %s" % (k, r.stop)); sys.exit(1)
        rows.append((c, struct.unpack("<8i", e.read(st['sets'], 32)), struct.unpack("<Q", e.read(isp + 0x320 + 24, 8))[0],
                     st['cap'], st['ev']))
    print("ae_init: AE_fsm_clear %d bytes, cmos_fsm_clear %d bytes, adjust_exposure %d cases" % (AE_SIZE, CMOS_SIZE, len(rows)))
    if out:
        with open(out, "w") as f:
            f.write("/* generated by tools/ko_emu/diff_t30_ae_init.py from the SDK-built tx-isp-t30.ko 4ea12e1f\n"
                    " * (AE_fsm_clear 0x2de80, cmos_fsm_clear 0x2d810 on pattern-filled contexts, adjust_exposure 0x29250).\n"
                    " * Fill pattern: byte i = i * 7 + salt (AE 0x5a, cmos 0x33). */\n")
            f.write("static const unsigned char t30_aei_ae[%d] = {" % AE_SIZE)
            f.write(",".join("%d" % b for b in ae_after) + "};\n")
            f.write("static const unsigned char t30_aei_cmos[%d] = {" % CMOS_SIZE)
            f.write(",".join("%d" % b for b in cmos_after) + "};\n")
            f.write("struct t30_aei_case { int mode; unsigned k; int step; int sets[8]; unsigned long long acc; int w334, w348;\n"
                    "\tint sets_out[8]; unsigned long long acc_out; int cap[3]; unsigned ev[2]; };\n")
            f.write("static const struct t30_aei_case t30_aei_cases[] = {\n")
            for c, so, ao, cp, evv in rows:
                f.write("\t{%d,%uu,%d,{%s},%luull,%d,%d,{%s},%luull,{%d,%d,%d},{%uu,%uu}},\n" % (
                    c['mode'], c['k'], s32(c['step']), ",".join(str(s32(x)) for x in c['sets']), c['acc'],
                    s32(c['w334']), s32(c['w348']), ",".join(str(x) for x in so), ao, cp[0], cp[1], cp[2], evv[0], evv[1]))
            f.write("};\n")


if __name__ == "__main__":
    main()
