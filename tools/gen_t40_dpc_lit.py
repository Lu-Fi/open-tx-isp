#!/usr/bin/env python3
# gen_t40_dpc_lit.py <workdir> <oem.ko> <objdump> <out.inc>
# Literal OEM defog chain (tisp_defog_*), same scheme as gen_t40_adr_lit.py:
#   <workdir>/prod.sym      objdump -t of the OEM module
#   <workdir>/defog/fnlist  functions to translate (one per line)
#   <workdir>/defog/<fn>.c  mips2c_literal.py output per function (CALL_DISPATCH, BSS_HI_ZERO, SYMTAB)
import sys, re, subprocess
W, KO, OD, OUT = sys.argv[1:5]
PFX = 'dpclit'
fns = open(f"{W}/dpc/fnlist").read().split()
def cname(f):   # tisp_defog_get_data.part.0 -> tisp_defog_get_data_part_0 (asm label kept in the driver)
    return re.sub(r'[.$]', '_', f)
syms = {}
for l in open(f"{W}/prod.sym"):
    p = l.split()
    if len(p) >= 6 and p[2] == 'O' and p[3] in ('.bss', '.data', '.rodata'):
        syms[p[5]] = (p[3], int(p[0], 16), int(p[4], 16))
SHARED = {'tparamsN', 'tispinfo', 'tispSecdInfo', 'tisp_tattr'}
# .text tail call by HI16/LO16 pair (jr t9 to a local function): target by hand from the asm
TEXTFIX = {}
bodies = {}
used = set()
for f in fns:
    t = open(f"{W}/dpc/{f}.c").read().split('\n')
    t = [l for l in t if not l.startswith('/*')]
    b = '\n'.join(t)
    for m in re.finditer(r'&([A-Za-z_$][A-Za-z_0-9$.]*)', b):
        used.add(m.group(1))
    bodies[f] = b
priv = sorted(s for s in used if s in syms and s not in SHARED)
def secbytes(sec):
    out = subprocess.run([OD, '-s', '-j', sec, KO], capture_output=True, text=True).stdout
    data = {}
    for l in out.split('\n'):
        m = re.match(r'\s*([0-9a-f]+) ((?:[0-9a-f]{2,8} ){1,4})', l)
        if not m: continue
        a = int(m.group(1), 16)
        hx = ''.join(m.group(2).split())
        for i in range(0, len(hx), 2):
            data[a + i // 2] = int(hx[i:i+2], 16)
    return data
secs = {s: secbytes(s) for s in ('.data', '.rodata')}
o = []
o.append('''/*
 * Literal mips2c DPC chain (defective pixel correction, TOP bit 4) from the
 * OEM sc830ai tx-isp-t40.ko: tisp_dpc_main_init (parameter refresh, noref /
 * ref register configuration, interpolation tables), tisp_dpc_refresh (gain
 * interpolation, called from the AE total-gain fan-out), tisp_dpc_dn_params_refresh
 * and tisp_dpc_main_deinit.  Generated by tools/gen_t40_dpc_lit.py with
 * tools/mips2c_literal.py; 0 unhandled opcodes, 0 unmapped.
 *
 * Why: TOP bit 4 was never released by the recovered driver while the sc830ai
 * linear bank enables DPC (vendor TOP 0x7FD9004D).  All DPC state is private
 * here (dpclit_*); tparamsN is shared.  No ISR / event: DPC is table driven.
 * Active only with t40_dpc_on=1 and t40_gates_oem_offset=1; TOP bit 4 is
 * cleared only when the init returned 0.
 */
static bool regtrace_t40_dpc_on;
module_param_named(t40_dpc_on, regtrace_t40_dpc_on, bool, 0644);
MODULE_PARM_DESC(t40_dpc_on, "1 (with t40_gates_oem_offset=1) runs the literal OEM DPC chain and clears TOP bit 4 after a successful init (default 0)");
static bool regtrace_t40_dpc_lit_active;
static int regtrace_dpc_lit_init_ret = -1;
static unsigned int regtrace_dpc_lit_refresh_count;
static unsigned int regtrace_dpc_lit_bad_call;
static uint32_t regtrace_dpc_lit_bad_target;
module_param_named(dpclit_init_ret, regtrace_dpc_lit_init_ret, int, 0444);
module_param_named(dpclit_refresh_count, regtrace_dpc_lit_refresh_count, uint, 0444);
module_param_named(dpclit_bad_call, regtrace_dpc_lit_bad_call, uint, 0444);
module_param_named(dpclit_bad_target, regtrace_dpc_lit_bad_target, uint, 0444);

static const char dpclit_str[] = "dpc";
''')
for s in priv:
    sec, a, z = syms[s]
    if sec == '.bss':
        o.append(f"static uint8_t {PFX}_{cname(s)}[{max(z,1)}] __attribute__((aligned(8)));")
    else:
        b = secs[sec]
        vals = ', '.join(f"0x{b.get(a+i,0):02x}" for i in range(z))
        o.append(f"static uint8_t {PFX}_{cname(s)}[{max(z,1)}] __attribute__((aligned(8))) = {{ {vals} }};")
anon = sorted({int(m, 16) for b in bodies.values()
               for m in re.findall(r'/\*UNMAPPED \.rodata\+0x([0-9a-f]+)\*/0', b)})
ro_starts = sorted(a for (sec, a, z) in syms.values() if sec == '.rodata')
for i, a in enumerate(anon):
    nxt = [x for x in ro_starts if x > a] + ([anon[i+1]] if i + 1 < len(anon) else [])
    z = min(min(nxt) - a if nxt else 256, 1024)
    b = secs['.rodata']
    vals = ', '.join(f"0x{b.get(a+k,0):02x}" for k in range(z))
    o.append(f"static const uint8_t {PFX}_ro_{a:x}[{z}] __attribute__((aligned(8))) = {{ {vals} }};")
o.append('')
for f in fns:
    o.append(f"static int32_t {PFX}_{cname(f)}_lit(uint32_t a0_in, uint32_t a1_in, uint32_t a2_in, uint32_t a3_in, uint32_t sp_in, uint32_t *v1_io, uint32_t v0_in);")
o.append(f"static uint32_t {PFX}_dispatch(uint32_t fn, uint32_t a0, uint32_t a1, uint32_t a2, uint32_t a3, uint32_t sp, uint32_t *v1, uint32_t v0);")
o.append(f"#define DPC_DISPATCH(r) {PFX}_dispatch((r), r_a0, r_a1, r_a2, r_a3, r_sp, &r_v1, r_v0)")
o.append('')
def fix(f, b):
    b = b.replace('ADR_DISPATCH', 'DPC_DISPATCH')
    b = re.sub(r'/\*UNMAPPED \.rodata\+0x([0-9a-f]+)\*/0', lambda m: f'{PFX}_ro_{m.group(1)}', b)
    b = re.sub(r'&\$LC\d+', f'{PFX}_str', b)
    if f in TEXTFIX:
        b = b.replace('&.text', '&' + TEXTFIX[f])
    def rp(m):
        n = m.group(1)
        if n in priv: return f'{PFX}_{cname(n)}'
        if n in fns and n != cname(n): return '&' + cname(n)
        return m.group(0)
    return re.sub(r'&([A-Za-z_][A-Za-z_0-9.]*)', rp, b)
for f in fns:
    o.append(f'''static int32_t {PFX}_{cname(f)}_lit(uint32_t a0_in, uint32_t a1_in, uint32_t a2_in, uint32_t a3_in, uint32_t sp_in, uint32_t *v1_io, uint32_t v0_in)
{{
    uint32_t r_v0 = v0_in, r_v1 = v1_io ? *v1_io : 0;
    uint32_t r_t0 = 0, r_t1 = 0, r_t2 = 0, r_t3 = 0, r_t4 = 0, r_t5 = 0;
    uint32_t r_t6 = 0, r_t7 = 0, r_t8 = 0, r_t9 = 0;
    uint32_t r_s0 = 0, r_s1 = 0, r_s2 = 0, r_s3 = 0, r_s4 = 0, r_s5 = 0;
    uint32_t r_s6 = 0, r_s7 = 0, r_s8 = 0, r_ra = 0, r_at = 0;
    uint32_t mips_lo = 0, mips_hi = 0, mips_cond = 0;
    uint32_t r_a0 = a0_in, r_a1 = a1_in, r_a2 = a2_in, r_a3 = a3_in;
    uint32_t r_sp = sp_in;

    (void)r_at; (void)r_ra; (void)r_t8; (void)r_t9; (void)mips_lo; (void)mips_hi;
    (void)mips_cond;
{fix(f, bodies[f])}
fn_exit:
    if (v1_io)
        *v1_io = r_v1;
    return (int32_t)r_v0;
}}
''')
d = [f'''static uint32_t {PFX}_dispatch(uint32_t fn, uint32_t a0, uint32_t a1, uint32_t a2, uint32_t a3, uint32_t sp, uint32_t *v1, uint32_t v0)
{{''']
for f in fns:
    d.append(f"    if (fn == (uint32_t)(uintptr_t)&{cname(f)})\n        return (uint32_t){PFX}_{cname(f)}_lit(a0, a1, a2, a3, sp, v1, v0);")
d.append(f'''    if (fn == (uint32_t)(uintptr_t)&system_reg_write)
        return (uint32_t)system_reg_write(a0, a1);
    if (fn == (uint32_t)(uintptr_t)&system_reg_read)
        return (uint32_t)system_reg_read(a0);
    if (fn == (uint32_t)(uintptr_t)&memcpy)
        return (uint32_t)(uintptr_t)memcpy((void *)(uintptr_t)a0, (const void *)(uintptr_t)a1, a2);
    if (fn == (uint32_t)(uintptr_t)&memset)
        return (uint32_t)(uintptr_t)memset((void *)(uintptr_t)a0, (int)a1, a2);
    if (fn == (uint32_t)(uintptr_t)&private_kmalloc)
        return (uint32_t)(uintptr_t)kmalloc(a0, (gfp_t)a1);
    if (fn == (uint32_t)(uintptr_t)&private_kfree || fn == (uint32_t)(uintptr_t)&kfree) {{
        kfree((void *)(uintptr_t)a0);
        return 0;
    }}
    regtrace_dpc_lit_bad_call++;
    regtrace_dpc_lit_bad_target = fn;
    return 0;
}}
''')
o.append(f'''/* one emulated MIPS stack per entry context */
#define DPCLIT_STACK 6144
static uint8_t {PFX}_stack_init[DPCLIT_STACK] __attribute__((aligned(8)));
static uint8_t {PFX}_stack_ctl[DPCLIT_STACK] __attribute__((aligned(8)));
#define DPCLIT_SP(s) ((uint32_t)(uintptr_t)((s) + DPCLIT_STACK - 64))

''')
o.append('\n'.join(d))
o.append(f'''
/* OEM tisp_day_or_night_s_ctrl -> tisp_dpc_dn_params_refresh(sensor) */
static int regtrace_dpc_dn_refresh_lit(void)
{{
    if (!regtrace_t40_dpc_lit_active)
        return 0;
    return (int)dpclit_tisp_dpc_dn_params_refresh_lit(0, 0, 0, 0, DPCLIT_SP({PFX}_stack_ctl), NULL, 0);
}}

/* OEM tisp_main_long_tgain_update -> tisp_dpc_refresh(sensor, tgain 16.16 log2) */
static void regtrace_dpc_refresh_lit(uint32_t tgain)
{{
    if (!regtrace_t40_dpc_lit_active)
        return;
    regtrace_dpc_lit_refresh_count++;
    (void)dpclit_tisp_dpc_refresh_lit(0, tgain, 0, 0, DPCLIT_SP({PFX}_stack_ctl), NULL, 0);
}}

static void regtrace_dpc_lit_cleanup(void)
{{
    if (!regtrace_t40_dpc_lit_active)
        return;
    regtrace_t40_dpc_lit_active = false;
    (void)dpclit_tisp_dpc_main_deinit_lit(0, 0, 0, 0, DPCLIT_SP({PFX}_stack_ctl), NULL, 0);
    printk(KERN_INFO "tx_isp_t40_recovered: dpc-lit deinit done\\n");
}}

static int regtrace_dpc_init_lit(void)
{{
    int ret = (int)dpclit_tisp_dpc_main_init_lit(0, 0, 0, 0, DPCLIT_SP({PFX}_stack_init), NULL, 0);

    regtrace_dpc_lit_init_ret = ret;
    regtrace_t40_dpc_lit_active = !ret;
    printk(KERN_INFO "tx_isp_t40_recovered: dpc-main-init-lit ret=%d bad_call=%u\\n",
           ret, regtrace_dpc_lit_bad_call);
    return ret;
}}
''')
open(OUT, 'w').write('\n'.join(o))
print("private symbols:", len(priv), "functions:", len(fns))
